/** One setting by id, or null. */
export function settingById(id) {
  return BY_ID.get(id) || null;
}

/** Every setting whose home is `home` ('section/page'), in registry order. */
export function settingsIn(home) {
  return SETTINGS.filter((entry) => entry.home === home);
}

/** The setting stored at a config path, or null. */
export function settingAtPath(path) {
  return SETTINGS.find((entry) => entry.path && entry.path.length === path.length && entry.path.every((k, i) => k === path[i])) || null;
}

/** Reads a key path from an object; undefined when any step is missing. */
export function readPath(obj, path) {
  let node = obj;
  for (const key of path) {
    if (node == null || typeof node !== 'object') return undefined;
    node = node[key];
  }
  return node;
}

const unset = (v) => v === undefined || v === null;

/** The box-wide value of a setting: what is saved, else its default. */
export function boxValue(entry, config = {}) {
  const e = typeof entry === 'string' ? settingById(entry) : entry;
  if (!e) return undefined;
  const v = e.path ? readPath(config, e.path) : undefined;
  return unset(v) ? clone(e.default) : v;
}

// An override's stored form, when it differs from the box value's (a box
// switch saved as true/false that a channel stores as 'on'/'off').
function fromOverride(entry, raw) {
  const map = entry.override && entry.override.values;
  if (!map) return raw;
  const hit = Object.entries(map).find(([, stored]) => stored === raw);
  if (!hit) return undefined;
  if (hit[0] === 'true') return true;
  if (hit[0] === 'false') return false;
  return hit[0];
}

/** The value a channel or block stores to override the box with `value`. */
export function toOverride(entry, value) {
  const map = entry.override && entry.override.values;
  return map && Object.prototype.hasOwnProperty.call(map, String(value)) ? map[String(value)] : value;
}

/** A channel's or block's own value for a setting, or undefined when it follows the level above. */
export function overrideValue(entry, owner, level = 'channel') {
  const e = typeof entry === 'string' ? settingById(entry) : entry;
  const key = e && e.override && e.override[level];
  if (!owner || !key) return undefined;
  const raw = readPath(owner, key);
  if (unset(raw) || raw === '') return undefined;
  return fromOverride(e, raw);
}

/**
 * The effective value of a setting: the block's own, else the channel's own,
 * else the box-wide value, else its default.
 * @param {string|object} id The setting id (or entry).
 * @param {object} [where] { ch, block, config }.
 * @returns {*} The value.
 */
export function settingFor(id, { ch = null, block = null, config = {} } = {}) {
  const e = typeof id === 'string' ? settingById(id) : id;
  if (!e) return undefined;
  const fromBlock = overrideValue(e, block, 'block');
  if (fromBlock !== undefined) return fromBlock;
  const fromChannel = overrideValue(e, ch, 'channel');
  if (fromChannel !== undefined) return fromChannel;
  return boxValue(e, config);
}

/** [path, default] for every setting written into the config at boot (setting-defaults.js). */
export function registryDefaults() {
  return SETTINGS.filter((entry) => entry.fill && entry.path).map((entry) => [entry.path, entry.default]);
}

/** The default of the setting stored at `path` (a copy), or undefined. */
export function registryDefaultForPath(path) {
  const e = settingAtPath(path);
  return e && !unset(e.default) ? clone(e.default) : undefined;
}

