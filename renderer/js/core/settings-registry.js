/**
 * Whether a LAN client may see and change this setting.
 * @param {object} entry A registry entry.
 * @returns {boolean} True for a plain box-wide value a remote may write.
 */
export function remoteEditable(entry) {
  if (!entry || !entry.path || entry.remote === false || entry.scope || entry.store || entry.fit) return false;
  if (HOST_ONLY_SECTIONS.includes(entry.path[0]) || !CLIENT_TYPES.has(entry.type)) return false;
  return !entry.dynamicChoices || !!CLIENT_CHOICES[entry.id];
}

/**
 * What GET /api/settings/registry sends the companion app: the sections and
 * pages, and every setting a remote may change, without any config values.
 * @returns {object} { version, sections, settings }.
 */
export function remoteSettingsCatalogue() {
  const settings = SETTINGS.filter(remoteEditable).map((e) => {
    const out = { id: e.id, path: e.path, label: e.label, help: e.help || '', type: e.type, home: e.home || '', level: e.level || 'advanced' };
    if (e.choices) out.choices = e.choices;
    if (CLIENT_CHOICES[e.id]) out.choicesFrom = CLIENT_CHOICES[e.id];
    if (e.range) out.range = e.range;
    if (e.scale) out.scale = e.scale;
    if (e.default !== undefined) out.default = e.default;
    if (e.dependsOn) out.dependsOn = e.dependsOn;
    if (e.synonyms) out.synonyms = e.synonyms;
    return out;
  });
  const sections = SECTIONS.map((s) => ({ id: s.id, label: s.label, pages: (s.pages || []).map((id) => ({ id, label: PAGE_LABELS[id] || id })) }));
  return { version: 1, sections, settings };
}

/**
 * Check and normalise a value a LAN client sent for a setting.
 * Numbers are clamped to the range (which is in shown units: stored = shown × scale).
 * @param {object} entry A registry entry.
 * @param {*} value The stored value to write; null or undefined resets it to the default.
 * @returns {{ok: boolean, value?: *, reason?: string}} The value to save, or why not.
 */
export function coerceSettingValue(entry, value) {
  if (!entry) return { ok: false, reason: 'no such setting' };
  if (value === null || value === undefined) return { ok: true, value: undefined };
  if (entry.type === 'switch') return typeof value === 'boolean' ? { ok: true, value } : { ok: false, reason: 'expected on or off' };
  if (entry.type === 'choice') {
    if (CLIENT_CHOICES[entry.id] === 'themes') return typeof value === 'string' && /^[\w.-]{1,64}$/.test(value) ? { ok: true, value } : { ok: false, reason: 'not a theme id' };
    if (CLIENT_CHOICES[entry.id] === 'channels') {
      if (value === 'last' || value === 'first') return { ok: true, value };
      return Number.isFinite(Number(value)) && value !== '' ? { ok: true, value: Number(value) } : { ok: false, reason: 'not a channel' };
    }
    const hit = (entry.choices || []).find(([v]) => String(v) === String(value));
    if (hit && hit[0] === '' && entry.default === '') return { ok: true, value: undefined };
    return hit ? { ok: true, value: hit[0] } : { ok: false, reason: 'not one of the choices' };
  }
  if (entry.type === 'number') {
    const n = typeof value === 'number' ? value : Number(value);
    if (!Number.isFinite(n) || value === '') return { ok: false, reason: 'expected a number' };
    const scale = entry.scale || 1;
    const r = entry.range || {};
    const shown = Math.min(r.max ?? Infinity, Math.max(r.min ?? -Infinity, n / scale));
    return { ok: true, value: Math.round(shown * scale * 1e6) / 1e6 };
  }
  if (entry.type === 'text') return typeof value === 'string' && value.length <= 500 ? { ok: true, value } : { ok: false, reason: 'expected text' };
  return { ok: false, reason: 'this setting is changed on the box' };
}
