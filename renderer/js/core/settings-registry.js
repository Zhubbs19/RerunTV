// The settings registry (docs/design/14 §3): every user-facing setting, defined
// once. Label, help, type, range, default, where it lives in setup (`home`,
// section/page), whether it is everyday or advanced (`level`), who may override
// it (`override`, a key path on a channel or block), whether the TV menu shows it
// (`tv`) and whether a LAN control client may change it (`remote`).
//
// What reads it:
//   - setup rows: the static rows in index.html are checked against it by
//     tests/settings-registry.test.js (label, help, range, choices), and the
//     Simple/Advanced view comes from `level`; Fit to time slots and the newer
//     rows are rendered from it;
//   - channel pages: OverrideRow (setup/override-row.js) for every `override`;
//   - the TV menu: tv/setup.js builds its sections from `tv`;
//   - search: channel overrides are search results ("Pause for ads · CH 67");
//   - defaults: setting-defaults.js writes every `fill` default into the config;
//   - the remote deny-list: main/config/host.js's REMOTE_DENIED_SETTINGS must
//     cover every `remote: false` path (tested);
//   - settingFor(): the one effective-value read, block then channel then box
//     then default.
//
// Stored value = shown value × `scale` (a % slider saving 0-1, seconds saving ms).
// `scope` is 'device' for settings saved on this device only (`store` says
// where) and 'app' for the splicer's own store; everything else is channels.json.
// Pure: no DOM and no app state; callers pass the config (S.config in the app).

import { REMOTE_BUTTON_ACTIONS, REMOTE_BUTTON_SLOTS, defaultButtonAction } from '../remote/input.js';

// "Open the guide" for an action id, "Nothing" for none.
function buttonActionLabel(id) {
  const hit = REMOTE_BUTTON_ACTIONS.find((a) => a.id === id);
  return hit ? hit.label : 'Nothing';
}

